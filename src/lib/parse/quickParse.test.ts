describe('parseQuick — тип записи', () => {
  it('«купить X» — покупка в список «Покупки»', () => {
    has(p('купить молоко'), { kind: 'list_item', listId: 'l-buy', title: 'молоко' });
  });

  it('«купить» в середине — обычная задача', () => {
    expect(p('сходить купить хлеб').kind).toBeUndefined();
  });

  it('«в список Фильмы» — пункт этого списка', () => {
    has(p('Дюна в список Фильмы'), { kind: 'list_item', listId: 'l-film', title: 'Дюна' });
  });

  it('список из нескольких слов и кавычки', () => {
    has(p('наушники в список «Идеи подарков» 30к'), {
      kind: 'list_item',
      listId: 'l-gift',
      price: 30000,
      title: 'наушники',
    });
  });

  it('незнакомый список — пункт без listId', () => {
    const r = p('шуруповёрт в список ремонт');
    expect(r.kind).toBe('list_item');
    expect(r.listId).toBe('l-buy');
    expect(r.title).toBe('шуруповёрт');
  });

  it('«мысль:» — заметка, текст не разбирается', () => {
    has(p('мысль: завтра в 15 всё поменять'), { kind: 'note', title: 'завтра в 15 всё поменять', date: undefined, time: undefined });
  });

  it('«Идея:» с эмодзи', () => {
    has(p('💡 Идея: подкаст про деньги'), { kind: 'note', emoji: '💡', title: 'подкаст про деньги' });
  });

  it('«напомни» — напоминание', () => {
    has(p('напомни завтра в 9 оплатить интернет'), {
      kind: 'reminder',
      date: '2026-10-01',
      time: '09:00',
      title: 'оплатить интернет',
    });
    expect(p('напомни мне про встречу').title).toBe('встречу');
  });

  it('«каждый месяц» — повторяющееся напоминание', () => {
    has(p('каждый месяц оплатить аренду 150к'), { kind: 'reminder', repeat: 'monthly', price: 150000, title: 'оплатить аренду' });
  });

  it('«ежегодно» + дата', () => {
    has(p('ежегодно день рождения мамы 14 октября'), { repeat: 'yearly', date: '2026-10-14', title: 'день рождения мамы' });
  });

  it('«каждый год» и «каждую неделю»', () => {
    expect(p('каждый год техосмотр').repeat).toBe('yearly');
    expect(p('каждую неделю уборка').repeat).toBe('weekly');
  });

  it('«каждый понедельник» — по неделям с ближайшего понедельника', () => {
    has(p('каждый понедельник планёрка'), { repeat: 'weekly', date: '2026-10-05', title: 'планёрка' });
  });

  it('«каждую среду» начинается сегодня, раз сегодня среда', () => {
    expect(p('каждую среду бассейн').date).toBe('2026-09-30');
  });

  it('«каждое утро» — ежедневно в 9:00', () => {
    has(p('каждое утро витамины'), { repeat: 'daily', time: '09:00' });
  });
});

describe('parseQuick — целиком', () => {
  it('пример из брифа', () => {
    const r = p('завтра в 15 на 30м #работа ^сайт ! позвонить маме');
    has(r, {
      title: 'позвонить маме',
      date: '2026-10-01',
      time: '15:00',
      minutes: 30,
      area: 'work',
      goalId: 'g-site',
      important: true,
    });
    expect(r.kind).toBeUndefined();
    expect(r.tokens.map(t => t.kind)).toEqual(['date', 'time', 'duration', 'area', 'goal', 'important']);
    expect(r.tokens.map(t => t.label)).toEqual(['Завтра', '15:00', '30 мин', 'Работа', '🚀 Запустить сайт студии', 'Важное']);
  });

  it('токены указывают на точные куски исходного текста', () => {
    const text = 'Завтра в 15:00 созвон на 30 мин #работа';
    const r = p(text);
    expect(r.tokens.map(t => text.slice(t.start, t.end))).toEqual(['Завтра', 'в 15:00', 'на 30 мин', '#работа']);
  });

  it('регистр, запятые и лишние пробелы', () => {
    has(p('  ЗАВТРА,   в 15:00 —  позвонить  '), { date: '2026-10-01', time: '15:00', title: 'позвонить' });
  });

  it('текст без токенов — только название', () => {
    const r = p('прочитать 2 главы');
    has(r, { title: 'прочитать 2 главы', date: undefined, time: undefined, minutes: undefined });
    expect(r.tokens).toEqual([]);
  });

  it('дата по умолчанию, если в тексте её нет', () => {
    expect(p('уборка', { defaultDate: '2026-09-30' }).date).toBe('2026-09-30');
    expect(p('завтра уборка', { defaultDate: '2026-09-30' }).date).toBe('2026-10-01');
  });

  it('время с датой по умолчанию не переносится на завтра', () => {
    expect(p('в 7 утра зарядка', { defaultDate: '2026-09-30' }).date).toBe('2026-09-30');
  });

  it('пустая строка', () => {
    has(p('   '), { title: '', tokens: [] });
  });
});

describe('помощники', () => {
  it('normalize сохраняет длину и заменяет ё', () => {
    expect(normalize('ЁЛКА Ёж')).toBe('елка еж');
    expect(normalize('🎸 Ё').length).toBe('🎸 Ё'.length);
  });

  it('stripSpans вырезает куски и чистит пробелы', () => {
    expect(stripSpans('завтра в 15 позвонить', [{ start: 0, end: 6 }, { start: 7, end: 11 }])).toBe('позвонить');
    expect(stripSpans('позвонить маме, завтра', [{ start: 16, end: 22 }])).toBe('позвонить маме');
  });

  it('dateLabel', () => {
    expect(dateLabel('2026-09-30', NOW)).toBe('Сегодня');
    expect(dateLabel('2026-10-01', NOW)).toBe('Завтра');
    expect(dateLabel('2026-10-02', NOW)).toBe('Послезавтра');
    expect(dateLabel('2026-10-03', NOW)).toBe('Сб, 3 окт');
    expect(dateLabel('2026-10-14', NOW)).toBe('14 окт');
    expect(dateLabel('2027-01-05', NOW)).toBe('5 янв 2027');
  });

  it('durationLabel', () => {
    expect(durationLabel(30)).toBe('30 мин');
    expect(durationLabel(60)).toBe('1 ч');
    expect(durationLabel(90)).toBe('1 ч 30 мин');
  });

  it('priceLabel', () => {
    expect(priceLabel(150000)).toBe('150 000 ₸');
  });

  it('matchGoal предпочитает начало названия', () => {
    const goals = [{ title: 'Большой сайт' }, { title: 'Сайт-визитка' }];
    expect(matchGoal('сайт', goals)?.title).toBe('Сайт-визитка');
    expect(matchGoal('', goals)).toBeUndefined();
  });
});
