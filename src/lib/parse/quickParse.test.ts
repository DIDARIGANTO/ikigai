import { describe, it, expect } from 'vitest';
import { dateLabel, durationLabel, matchGoal, normalize, parseQuick, priceLabel, stripSpans } from './quickParse';
import type { ParseContext } from './quickParse';

// Среда, 30 сентября 2026, 10:00 по местному времени.
const NOW = new Date(2026, 8, 30, 10, 0);
const ctx: ParseContext = {
  now: NOW,
  goals: [
    { id: 'g-site', title: 'Запустить сайт студии', emoji: '🚀' },
    { id: 'g-clip', title: 'Съёмка клипа' },
    { id: 'g-eng', title: 'Английский B2' },
  ],
  lists: [
    { id: 'l-buy', title: 'Покупки' },
    { id: 'l-film', title: 'Фильмы' },
    { id: 'l-gift', title: 'Идеи подарков' },
  ],
};
/** Как toMatchObject, но `undefined` в образце значит «поле не распознано». */
function has(r: object, shape: Record<string, unknown>) {
  for (const [k, v] of Object.entries(shape)) expect((r as Record<string, unknown>)[k], k).toEqual(v);
}
const p = (text: string, extra: Partial<ParseContext> = {}) => parseQuick(text, { ...ctx, ...extra });

describe('parseQuick — даты', () => {
  it.each([
    ['сегодня', '2026-09-30'],
    ['завтра', '2026-10-01'],
    ['послезавтра', '2026-10-02'],
    ['на завтра', '2026-10-01'],
    ['в пн', '2026-10-05'],
    ['во вторник', '2026-10-06'],
    ['в пятницу', '2026-10-02'],
    ['пт', '2026-10-02'],
    ['в субботу', '2026-10-03'],
    ['в воскресенье', '2026-10-04'],
    ['в следующую пятницу', '2026-10-09'],
    ['на следующей неделе', '2026-10-05'],
    ['на следующей неделе в среду', '2026-10-07'],
    ['в четверг на следующей неделе', '2026-10-08'],
    ['через 3 дня', '2026-10-03'],
    ['через два дня', '2026-10-02'],
    ['через неделю', '2026-10-07'],
    ['через 2 недели', '2026-10-14'],
    ['через месяц', '2026-10-30'],
    ['14 октября', '2026-10-14'],
    ['5 окт.', '2026-10-05'],
    ['к 1 ноября', '2026-11-01'],
    ['14.10', '2026-10-14'],
    ['14.10.2027', '2027-10-14'],
    ['на 3.11', '2026-11-03'],
    ['1 сентября', '2027-09-01'],
    ['30 сентября', '2026-09-30'],
    ['на выходных', '2026-10-03'],
  ])('«%s» → %s', (text, date) => {
    const r = p(`${text} дело`);
    expect(r.date).toBe(date);
    expect(r.title).toBe('дело');
  });

  it('тот же день недели — это следующая неделя', () => {
    expect(p('в среду созвон').date).toBe('2026-10-07');
  });

  it('несуществующая дата остаётся текстом', () => {
    const r = p('отчёт 31.02');
    expect(r.date).toBeUndefined();
    expect(r.title).toBe('отчёт 31.02');
  });

  it('дата с годом в прошлом не переносится', () => {
    expect(p('14.10.2025 архив').date).toBe('2025-10-14');
  });

  it('первая дата побеждает, вторая остаётся в названии', () => {
    const r = p('завтра перенести на 14.10');
    expect(r.date).toBe('2026-10-01');
    expect(r.title).toBe('перенести на 14.10');
  });
});

describe('parseQuick — время', () => {
  it.each([
    ['в 15:00', '15:00'],
    ['15:30', '15:30'],
    ['к 9:05', '09:05'],
    ['в 15', '15:00'],
    ['в 15.30', '15:30'],
    ['в 3 дня', '15:00'],
    ['в 12 дня', '12:00'],
    ['в 8 вечера', '20:00'],
    ['в 2 ночи', '02:00'],
    ['в 12 ночи', '00:00'],
    ['вечером', '19:00'],
    ['днём', '13:00'],
    ['в полдень', '12:00'],
    ['в полночь', '00:00'],
    ['в 3', '15:00'],
    ['в 7 часов', '07:00'],
  ])('«%s» → %s', (text, time) => {
    const r = p(`завтра ${text} дело`);
    expect(r.time).toBe(time);
    expect(r.title).toBe('дело');
    expect(r.minutes).toBeUndefined();
  });

  it('«в 7 утра» без даты — завтра, раз 7:00 уже прошло', () => {
    const r = p('пробежка в 7 утра');
    expect(r.time).toBe('07:00');
    expect(r.date).toBe('2026-10-01');
  });

  it('время позже «сейчас» без даты — сегодня', () => {
    has(p('в 15:00 созвон'), { time: '15:00', date: '2026-09-30' });
  });

  it('«утром» без даты — завтра', () => {
    has(p('утром зарядка'), { time: '09:00', date: '2026-10-01' });
  });

  it('«завтра вечером в 8» → 20:00', () => {
    has(p('завтра вечером в 8 кино'), { date: '2026-10-01', time: '20:00', title: 'кино' });
  });

  it('«утром в 5» → 05:00', () => {
    has(p('завтра утром в 5 поезд'), { time: '05:00', title: 'поезд' });
  });

  it('невозможный час остаётся текстом', () => {
    const r = p('в 25 дело');
    expect(r.time).toBeUndefined();
    expect(r.title).toBe('в 25 дело');
  });

  it('«через 2 часа» — сегодня в 12:00', () => {
    has(p('через 2 часа перезвонить'), { date: '2026-09-30', time: '12:00', title: 'перезвонить' });
  });

  it('«через 30 минут» — сегодня в 10:30', () => {
    has(p('через 30 минут выйти'), { time: '10:30', minutes: undefined, title: 'выйти' });
  });

  it('«с Аней» — не время', () => {
    const r = p('встреча с Аней');
    expect(r.time).toBeUndefined();
    expect(r.title).toBe('встреча с Аней');
  });
});

describe('parseQuick — длительность', () => {
  it.each([
    ['30м', 30],
    ['30 мин', 30],
    ['45 минут', 45],
    ['1ч', 60],
    ['1.5ч', 90],
    ['1,5 часа', 90],
    ['90 минут', 90],
    ['на час', 60],
    ['на полчаса', 30],
    ['на полтора часа', 90],
    ['1ч 30м', 90],
    ['на 2 часа', 120],
    ['на 30м', 30],
  ])('«%s» → %i мин', (text, minutes) => {
    const r = p(`уборка ${text}`);
    expect(r.minutes).toBe(minutes);
    expect(r.title).toBe('уборка');
    expect(r.time).toBeUndefined();
  });

  it('«в 15» — время, «15 минут» — длительность', () => {
    has(p('созвон в 15'), { time: '15:00', minutes: undefined });
    has(p('созвон 15 минут'), { time: undefined, minutes: 15 });
  });

  it('«14 октября» — дата, а не длительность', () => {
    has(p('14 октября сдать'), { date: '2026-10-14', minutes: undefined });
  });

  it('«30 мая» — дата, хотя «м» похоже на минуты', () => {
    has(p('30 мая отпуск'), { date: '2027-05-30', minutes: undefined });
  });

  it('время и длительность вместе', () => {
    has(p('в 15 на 30м созвон'), { time: '15:00', minutes: 30, title: 'созвон' });
  });
});

describe('parseQuick — теги, цель, важность, эмодзи', () => {
  it('#работа и #личное', () => {
    has(p('отчёт #работа'), { area: 'work', title: 'отчёт' });
    has(p('#Личное йога'), { area: 'personal', title: 'йога' });
  });

  it('незнакомый тег остаётся в названии', () => {
    has(p('план #идеи'), { area: undefined, title: 'план #идеи' });
  });

  it('^цель по началу слова, без регистра', () => {
    expect(p('макет ^сайт').goalId).toBe('g-site');
    expect(p('макет ^САЙТ').goalId).toBe('g-site');
    expect(p('слова ^англ').goalId).toBe('g-eng');
  });

  it('^цель с «ё» и «е» одинаково', () => {
    expect(p('раскадровка ^съемка').goalId).toBe('g-clip');
  });

  it('^цель по вхождению, если нет начала слова', () => {
    expect(p('текст ^студ').goalId).toBe('g-site');
    expect(p('текст ^тудии').goalId).toBe('g-site');
  });

  it('незнакомая ^цель остаётся текстом', () => {
    has(p('текст ^марс'), { goalId: undefined, title: 'текст ^марс' });
  });

  it('«!» отдельным словом — важная', () => {
    has(p('! налоги'), { important: true, title: 'налоги' });
    has(p('налоги !!'), { important: true, title: 'налоги' });
  });

  it('«Ура!» — не важность', () => {
    has(p('Ура!'), { important: undefined, title: 'Ура!' });
  });

  it('эмодзи в начале — плитка', () => {
    has(p('🎸 репетиция'), { emoji: '🎸', title: 'репетиция' });
    has(p('👩🏽‍💻 код-ревью'), { emoji: '👩🏽‍💻', title: 'код-ревью' });
  });

  it('эмодзи в середине остаётся в тексте', () => {
    expect(p('купил 🎸 наконец').emoji).toBeUndefined();
  });
});

