/** Поиск: каждое слово запроса должно совпасть с началом одного из слов названия. */
export function searchEmoji(query: string): string[] {
  const words = query.trim().toLowerCase().replace(/ё/g, 'е').split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е');
  return Object.entries(EMOJI_NAMES)
    .filter(([, names]) => {
      const tokens = norm(names).split(' ');
      return words.every(w => tokens.some(t => t.startsWith(w)));
    })
    .map(([e]) => e);
}
