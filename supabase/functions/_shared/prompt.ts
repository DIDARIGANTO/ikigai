/**
 * Подсказка для ИИ и проверка его ответа. Чистый модуль (без Deno и сети): его проверяют тесты веб-проекта
 * (`src/lib/domain/botPrompt.test.ts`), а `ai.ts` только отправляет запрос.
 */
import type { ParsedItem } from './render.ts';

export interface PromptContext {
  nowLocal: string;
  timezone: string;
  lists: string[];
  goals: { id: string; title: string }[];
  correction?: string;
}

/** Больше дел из одного сообщения не берём: это защита от разросшегося ответа, а не ограничение для человека. */
export const MAX_ITEMS = 30;

export function buildSystemPrompt(ctx: PromptContext): string {
  return `Ты разбираешь сообщения владельца личного планировщика Ikigai на структурированные элементы.
Сейчас: ${ctx.nowLocal} (${ctx.timezone}). Неделя начинается с понедельника.
Правила:
- Дела с датой/временем или глаголом действия → task. «в пятницу» = ближайшая пятница; «на следующей неделе в среду» = среда следующей недели; «через неделю» = +7 дней. Без даты — task без date.
- «купить X» → list_item в список «Купить» (или другой подходящий из списка пользователя: ${ctx.lists.join(', ') || 'Купить'}).
- Дни рождения, «каждый год/месяц/день», годовщины, оплаты по числам → reminder с repeat. Для ДР ставь date текущего или следующего года.
- «по будням», «каждый будний/рабочий день», «в будни» → reminder с repeat=weekdays (понедельник–пятница); date — сегодня, а если сегодня выходной, ближайший понедельник.
- «идея:», «есть идея», «придумал» — мысль, как что-то сделать, запустить или улучшить (бизнес, продукт, проект) → idea.
- «мысль:», размышления, всё, что не дело, не покупка и не идея → note.
- Работа, клиенты, проекты, отчёты → area work; остальное personal.
- Если явно относится к цели из списка — goal_id. Цели: ${ctx.goals.map(g => `${g.id}=${g.title}`).join('; ') || 'нет'}.
- Названия — коротко, с большой буквы, без точки в конце.
Диктовка:
- Сообщение часто надиктовано голосом и распознано машиной: без знаков препинания, с оговорками, повторами и словами-паразитами («ну», «короче», «значит», «эээ»). Выкинь паразитов, смысл не меняй, очевидные ошибки распознавания («по звонить» → «позвонить») исправь.
- В одном потоке обычно несколько дел: «позвонить маме потом купить хлеб и ещё в пятницу отправить отчёт» → три элемента. Делай по одному элементу на каждое дело, не склеивай их; перечисление через «и», «потом», «ещё», «также», запятую — это разные дела.
- Время словами переводи в HH:mm по 24-часовым часам: «в три дня» = 15:00, «в восемь вечера» = 20:00, «в десять утра» = 10:00. Если часть суток не названа, выбери наиболее вероятную для такого дела.
${ctx.correction ? `Пользователь поправил предыдущий разбор: «${ctx.correction}». Учти это.` : ''}`;
}

const TYPES = new Set(['task', 'reminder', 'list_item', 'note', 'idea']);
const REPEATS = new Set(['none', 'daily', 'weekdays', 'weekly', 'monthly', 'yearly']);

/** Модель может вернуть что угодно, поэтому в базу уходят только элементы известного типа с непустым названием. */
export function sanitizeItems(items: unknown): ParsedItem[] {
  if (!Array.isArray(items)) return [];
  return (items as Record<string, unknown>[])
    .filter(i => i && typeof i === 'object' && TYPES.has(i.type as string) && typeof i.title === 'string' && i.title.trim())
    .slice(0, MAX_ITEMS)
    .map(i => ({
      ...i,
      title: String(i.title).trim().slice(0, 200),
      // Повтор вне списка (модель могла выдумать «hourly») превращаем в разовое: иначе веб-приложение такую строку отбросит.
      ...(i.repeat !== undefined && !REPEATS.has(i.repeat as string) ? { repeat: 'none' } : {}),
    })) as unknown as ParsedItem[];
}
